/**
 * Données de « La roue des mots » (analyse des traits sémantiques).
 *
 * Chaque objet déclare, pour chaque axe, ses traits :
 * - `oui` : vrais et caractéristiques — proposés comme bonnes réponses et comme indices ;
 * - `aussi` : vrais, possibles ou discutables — jamais proposés comme bonne réponse,
 *   mais jamais non plus comme piège.
 * Tout trait de la réserve de la famille qui n'est ni dans `oui` ni dans `aussi` est
 * considéré comme FAUX pour cet objet et peut servir de piège. En ajoutant un objet ou un
 * trait, relire la réserve entière avec cette règle en tête.
 *
 * Les traits sont écrits sans sujet ; le jeu ajoute « Il » ou « Elle » selon le genre.
 * `f` = forme au féminin quand l'adjectif s'accorde.
 *
 * Les associations (« ça fait penser à ») forment une réserve commune : un piège n'est
 * tiré que parmi les associations des objets d'une AUTRE famille, pour rester loin du
 * thème (on ne propose pas « un fermier » pour la vache, il est dans `aussi`).
 */

